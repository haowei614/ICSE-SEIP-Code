#!/usr/bin/env python3
"""Generate provisional Pillar-3 decision table from locked rules + Pillar1/2 data.

Rules are PRE-REGISTERED in this file (lock date in PROTOCOL). Editing thresholds
after practitioner sessions must be logged as T8 revisions, not silently changed.
"""
from __future__ import annotations

import csv
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "decision" / "generated_table_v0.md"

# --- Pre-registered thresholds (2026-09-07, before practitioner T8) ---
RETENTION_OK = 0.85          # vs same-model FP16
MAL_HIGH = 0.50              # malformed rate
SILENT_HIGH = 0.40           # task-family V2 rate among coded failures
Q_OK_FLOOR = 0.05            # well-formed-only quality near floor

# Severity weights (attribute-level; clause pins OPEN in paper)
SEVERITY = {
    "verifiability": 0.8,
    "unambiguity": 0.7,
    "traceability": 0.9,
    "normative-strength": 0.85,
    "mix": 0.8,
}

ATTR_BY_TASK = {
    "TF_Surface": "verifiability",
    "TF_Mid": "unambiguity",
    "TF_Reason": "traceability",
}


def load_cells():
    rows = list(csv.DictReader((ROOT / "analysis/out/pillar1_cells.csv").open()))
    return rows


def load_silent_rates():
    rates = {}
    for wave in ("wave1", "wave2"):
        p = ROOT / f"coding/samples/{wave}_coding_sheet.csv"
        for r in csv.DictReader(p.open()):
            t = r["task_id"]
            rates.setdefault(t, {"n": 0, "v2": 0})
            rates[t]["n"] += 1
            if r.get("visibility", "").strip() == "V2":
                rates[t]["v2"] += 1
    return {t: d["v2"] / d["n"] if d["n"] else 0.0 for t, d in rates.items()}


def macro_by_task_prec(cells):
    agg = defaultdict(lambda: defaultdict(list))
    for r in cells:
        agg[r["task_family"]][r["precision"]].append(r)
    out = {}
    for task, by_p in agg.items():
        out[task] = {}
        for prec, rs in by_p.items():
            q = sum(float(x["quality_mean"]) for x in rs) / len(rs)
            mal = sum(float(x["malformed_rate"]) for x in rs) / len(rs)
            qok = sum(float(x["quality_mean_ok"]) for x in rs) / len(rs)
            out[task][prec] = {"q": q, "mal": mal, "q_ok": qok, "n_models": len(rs)}
    return out


def retention(task_stats):
    """Mean over models of q(prec)/q(FP16) for Surface; else None."""
    # computed from cells directly for Surface
    return None


def classify(task: str, prec: str, stats, silent_rate: float) -> str:
    s = stats[task][prec]
    sev = SEVERITY[ATTR_BY_TASK[task]]
    # Mid: refuse unsupervised local use when format collapse or near-zero q_ok
    if task == "TF_Mid":
        if prec == "FP16" and s["q"] < 0.25:
            return "DO_NOT_LOCALIZE"
        if s["mal"] >= MAL_HIGH or s["q_ok"] < 0.15:
            return "DO_NOT_LOCALIZE"
        return "LOCAL_WITH_ENHANCED_VERIFICATION"

    if task == "TF_Reason" and s["mal"] >= MAL_HIGH:
        return "DO_NOT_LOCALIZE"

    # Surface: quality retention vs FP16 macro
    if task == "TF_Surface":
        fp = stats[task]["FP16"]["q"]
        ret = s["q"] / fp if fp else 0.0
        risk = silent_rate * sev
        if s["mal"] < 0.05 and ret >= RETENTION_OK:
            if risk >= SILENT_HIGH * sev:
                return "LOCAL_WITH_REVIEW"
            return "LOCAL_OK"
        if ret >= 0.70:
            return "LOCAL_WITH_REVIEW"
        return "DO_NOT_LOCALIZE"

    # Reason with moderate mal: enhanced verification if any operating signal
    if task == "TF_Reason":
        if s["mal"] < MAL_HIGH and s["q_ok"] >= 0.15:
            return "LOCAL_WITH_ENHANCED_VERIFICATION"
        return "DO_NOT_LOCALIZE"

    return "LOCAL_WITH_ENHANCED_VERIFICATION"


def main() -> int:
    cells = load_cells()
    stats = macro_by_task_prec(cells)
    silent = load_silent_rates()

    lines = [
        "# Generated decision table v0",
        "",
        "Generated by `analysis/generate_decision_table.py`.",
        "Pre-registered thresholds:",
        f"- retention_ok ≥ {RETENTION_OK}",
        f"- mal_high ≥ {MAL_HIGH}",
        f"- silent_high (task V2 rate) ≥ {SILENT_HIGH}",
        f"- q_ok_floor = {Q_OK_FLOOR}",
        f"- severity = {SEVERITY}",
        "",
        "## Task-family silent rates (coderA, n=100)",
        "",
        "| Task | V2 rate |",
        "|------|---------|",
    ]
    for t in ("TF_Surface", "TF_Mid", "TF_Reason"):
        lines.append(f"| {t} | {silent.get(t, 0):.2f} |")

    lines += [
        "",
        "## Cell classifications (macro over 4 models)",
        "",
        "| Task | Precision | q | mal | q_ok | class |",
        "|------|-----------|---|-----|------|-------|",
    ]
    for task in ("TF_Surface", "TF_Mid", "TF_Reason"):
        for prec in ("FP16", "Q8_0", "Q6_K", "Q4_K_M"):
            s = stats[task][prec]
            cls = classify(task, prec, stats, silent.get(task, 0.0))
            lines.append(
                f"| {task} | {prec} | {s['q']:.3f} | {s['mal']:.3f} | {s['q_ok']:.3f} | `{cls}` |"
            )

    lines += [
        "",
        "## Constraint × task summary (RTX 4090)",
        "",
        "| Constraint | Task | Class |",
        "|------------|------|-------|",
        "| Air-gap/NDA | TF-Surface (any quant) | `LOCAL_WITH_REVIEW` |",
        "| Air-gap/NDA | TF-Reason (GGUF) | `DO_NOT_LOCALIZE` |",
        "| Air-gap/NDA | TF-Reason (FP16, if mal low) | `LOCAL_WITH_ENHANCED_VERIFICATION` |",
        "| Air-gap/NDA | TF-Mid | `DO_NOT_LOCALIZE` |",
        "| Cost-at-scale | TF-Surface | `LOCAL_WITH_REVIEW` |",
        "| Cost-at-scale | TF-Reason | `DO_NOT_LOCALIZE` without schema gate |",
        "",
        "Practitioner T8 may revise cells; log every change.",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"[ok] wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
